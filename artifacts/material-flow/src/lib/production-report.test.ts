import assert from "node:assert/strict";
import type { Job } from "@workspace/api-client-react";
import { sampleJobs } from "../../../api-server/src/lib/material";
import { buildProductionCsv, csvCell, filterReportJobs, type ReportFilters } from "./production-report";

const f: ReportFilters = { from: "", to: "", material: "", machine: "", product: "", unit: "", status: "approved", includeSamples: false };
const base = (sampleJobs() as unknown as Job[])[0];
const a = { ...base, id: "a", number: '=HYPERLINK("bad")', date: "2026-10-11", isSample: false, status: "approved", good: null, unit: "kg" } as Job;
const b = { ...a, id: "b", status: "submitted", unit: "sheets" } as Job;
assert.equal(filterReportJobs([a,b], f).length, 1);
assert.equal(filterReportJobs([a,b], {...f, status:"all"}).length, 2);
assert.equal(filterReportJobs([a,b], {...f, status:"both", unit:"sheets"})[0].id, "b");
assert.equal(filterReportJobs([a], {...f, from:a.date, to:a.date}).length, 1);
assert.equal(filterReportJobs([a], {...f, material:"unknown"}).length, 0);
assert.equal(filterReportJobs([{...a,isSample:true}], f).length, 0);
assert.equal(filterReportJobs([{...a,isSample:true}], {...f,includeSamples:true}).length, 1);
assert.throws(()=>filterReportJobs([a], {...f,from:"2026-10-12",to:"2026-10-11"}));
assert.equal(csvCell('=2+2'), '"\'=2+2"');
assert.equal(csvCell(' \t@SUM(A1)'), '"\' \t@SUM(A1)"');
assert.equal(csvCell('a,"b"\nc'), '"a,""b""\nc"');
assert.equal(csvCell(null), '""');
const csv = buildProductionCsv([a,b], {...f,status:"all"}, "Test company");
assert.ok(csv.startsWith("\uFEFF"));
assert.ok(csv.includes("'=HYPERLINK"));
assert.ok(csv.includes("Submitted - awaiting review"));
assert.ok(csv.includes("no combined totals"));
assert.ok(csv.includes('"kg"') && csv.includes('"sheets"'));
assert.ok(csv.includes("Recorded scrap entries"));
console.log("Production report checks passed.");
