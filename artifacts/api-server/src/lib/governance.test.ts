import { strict as assert } from "node:assert";
import { approvalIssue, jobAudit, invitationExpiry, memberView } from "./governance";
import { calculated, sampleJobs } from "./material";
const checklist={specifications:true,quantities:true,scrapReasons:true};
const sample=sampleJobs()[0];
assert.match(approvalIssue(sample,{})!,/Confirm/);
assert.match(approvalIssue(sample,{checklist:{...checklist,quantities:false}})!,/Confirm/);
assert.equal(approvalIssue(sample,{checklist}),null);
const below=calculated({...sample,plannedYield:80});
assert.match(approvalIssue(below,{checklist,comment:" "})!,/Explain/);
assert.equal(approvalIssue(below,{checklist,comment:"Reviewed against the actual cutting requirements."}),null);
assert.match(approvalIssue({...sample,pendingRework:1},{checklist})!,/Explain/);
assert.equal(approvalIssue({...sample,plannedYield:75},{checklist}),null);
const actor={name:"Supervisor",userId:"test-actor",role:"supervisor"};
const after={...sample,status:"approved"};
const event=jobAudit(actor,"approve",sample,after,"Checked",checklist);
assert.equal(event.version,sample.version+1);
assert.equal(event.actorRole,"supervisor");
assert.equal(event.actorId,"test-actor");
assert.equal(event.fromStatus,"submitted");
assert.equal(event.toStatus,"approved");
assert.deepEqual(event.checklist,checklist);
assert.deepEqual(event.fieldChanges,[]);
const changed=jobAudit(actor,"updated",sample,{...sample,good:901,notes:"Corrected"},"Scale reading corrected.");
assert.deepEqual(changed.fieldChanges.find(f=>f.field==="good"),{field:"good",before:"900",after:"901"});
assert.equal(sample.good,900);
const expiry=invitationExpiry();
assert.ok(Math.abs(expiry.getTime()-Date.now()-7*86400000)<1000);
assert.equal(memberView({inviteExpiresAt:expiry}).inviteExpiresAt,expiry.toISOString());
assert.equal(memberView({inviteExpiresAt:null}).inviteExpiresAt,null);
console.log("Review and traceability regression checks passed.");
